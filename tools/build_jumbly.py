#!/usr/bin/env python3
"""Build public/words-jumbly.js for Jumbly (find every word hidden in six letters).

Inputs (already in the repo, so no downloads):
  public/words-boxed.js  BOXED_VALID - ENABLE-style dictionary (no proper nouns)
                         BOXED_AVOID - words never shown as answers
Commonness comes from wordfreq (pip install wordfreq).

Each puzzle = one common 6-letter root word. "words" are the common words
(3-6 letters) players must find; "bonus" are other valid words that are
accepted for extra points but never required.

Usage:  pip install wordfreq && python3 tools/build_jumbly.py
"""
import json
import random
import re
from collections import Counter
from pathlib import Path

import wordfreq

ROOT = Path(__file__).resolve().parent.parent
BOXED = (ROOT / "public" / "words-boxed.js").read_text()


def js_list(name):
    m = re.search(r"const %s = \"([^\"]*)\"" % name, BOXED)
    if m:
        return m.group(1).split()
    m = re.search(r"const %s = \"([^\"]*)\"\.split" % name, BOXED)
    return m.group(1).split() if m else []


VALID = {w for w in js_list("BOXED_VALID") if w.isalpha() and w.islower() and 3 <= len(w) <= 6}
AVOID = set(js_list("BOXED_AVOID"))
VALID -= AVOID

REQUIRED_ZIPF = 3.5   # roughly "words most adults know"
ROOT_ZIPF = 3.8       # the 6-letter word itself should be familiar
MIN_WORDS, MAX_WORDS = 9, 26
COUNT = 400
EPOCH = "2026-11-16"


def zipf(w):
    return wordfreq.zipf_frequency(w, "en")


# Short words need to be much more common before we *require* them, otherwise
# abbreviations and slang (mon, rom, tho) sneak in. Those still count as bonus.
NOT_REQUIRED = set("""
mon rom tho nah yah ahi ado ain bra cos dis dom fab fax gal gee hmm huh lol mic nan nay oho ooh pic rad rev sis tat ted tis vet vid yea yep yon zed
ens ems pes eds res ers ors tis tes ids tae nae
bach brit cain casa kane lowe howe gen sec doc bro pro ups dang darn gosh lima hart hath
dope dorm gore euro euros expo coke lite labs jones inter feds docs cons bros ions cues
""".split())


# Names and rude words are never required (ENABLE/SCOWL accept many as
# obscure senses, e.g. "alec", "beth", "kris"). Census first names come from
# the `names` package; KEEP_NAMES are everyday words that are also names.
try:
    import names as _names_pkg
    _nd = Path(_names_pkg.__file__).parent
    NAMES = set()
    for fn in ("dist.male.first", "dist.female.first"):
        for line in (_nd / fn).read_text().splitlines():
            if line.split():
                NAMES.add(line.split()[0].lower())
except ImportError:  # pip install names
    NAMES = set()
KEEP_NAMES = set("""
art bill bob buck carol case chance chase chip clay cliff colt dale dawn dean
dell derby drew earl ernest faith fern ford frank gale gay gene glen grace
grant hale hall hank hope hunter iris ivy jack jay jean jewel joy june king
lane lark lee lily mack major mark marsh mason may mel miles mint misty
nick norm ola olive ore page pat patience pearl penny pierce rich rob robin
rock rod roe rose ruby rusty sage sandy scott shad sky son star sterling
sue summer tad tam tom tommy ty van vera ward wells wes will win wolf
""".split())
RUDE = set("""
anal anus arse ass bong boob boobs butt cock crap cum cunt damn dick dildo
dong dyke fag fart fuck gay gays homo hooker horny jizz meth nazi nude nudes
penis piss porn prick pube pubes rape raped sex sexy shit slut tit tits turd
twat weed whore
""".split())


def required_ok(w):
    if w in NOT_REQUIRED or w in RUDE:
        return False
    if w in NAMES and w not in KEEP_NAMES:
        return False
    return zipf(w) >= (4.3 if len(w) == 3 else REQUIRED_ZIPF)


def fits(word, pool):
    need = Counter(word)
    return all(pool[ch] >= n for ch, n in need.items())


common = {w for w in VALID if required_ok(w)}
roots = sorted(w for w in common if len(w) == 6 and zipf(w) >= ROOT_ZIPF)

puzzles = []
seen_sets = set()
for root in roots:
    pool = Counter(root)
    req = sorted((w for w in common if fits(w, pool)), key=lambda w: (len(w), w))
    if not (MIN_WORDS <= len(req) <= MAX_WORDS):
        continue
    key = "".join(sorted(root))
    if key in seen_sets:  # anagram roots (e.g. listen/silent) would repeat a board
        continue
    seen_sets.add(key)
    bonus = sorted((w for w in VALID if fits(w, pool) and w not in req and w not in RUDE), key=lambda w: (len(w), w))
    puzzles.append({"root": root, "words": req, "bonus": bonus})

random.Random(20261116).shuffle(puzzles)
puzzles = puzzles[:COUNT]

out = ROOT / "public" / "words-jumbly.js"
out.write_text(
    "// Generated by tools/build_jumbly.py - do not edit by hand.\n"
    f'const JUMBLY_EPOCH = "{EPOCH}";\n'
    f"const JUMBLY_PUZZLES = {json.dumps(puzzles, separators=(',', ':'))};\n"
)
print(f"{len(roots)} candidate roots -> {len(puzzles)} puzzles -> {out} ({out.stat().st_size // 1024} KB)")
for p in puzzles[:3]:
    print(p["root"], len(p["words"]), p["words"][:12], "| bonus", len(p["bonus"]))
