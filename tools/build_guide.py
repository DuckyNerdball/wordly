#!/usr/bin/env python3
"""Build public/words-guide.js: English words 3-15 letters, bucketed by word frequency (zipf x10),
used by Crossy's Guided Look to rank candidate fills. Requires: pip install wordfreq"""
import json, os, re
from collections import defaultdict
from wordfreq import top_n_list, zipf_frequency
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "public", "words-guide.js")
by = defaultdict(lambda: defaultdict(list))
seen = set()
for w in top_n_list("en", 250000):
    if not re.fullmatch(r"[a-z]{3,15}", w) or w in seen:
        continue
    seen.add(w)
    z = int(round(zipf_frequency(w, "en") * 10))
    if z < 15:
        continue
    by[len(w)][z].append(w)
data = {str(L): [[z, " ".join(ws)] for z, ws in sorted(b.items(), reverse=True)] for L, b in sorted(by.items())}
with open(OUT, "w") as fh:
    fh.write("// Generated by tools/build_guide.py - do not edit by hand.\n")
    fh.write("// Word frequencies from wordfreq (https://github.com/rspeer/wordfreq), data licensed CC BY-SA 4.0.\n")
    fh.write("// { length: [[zipf*10, 'word word ...'], ...] } - most common first.\n")
    fh.write("window.CROSSY_GUIDE_WORDS = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(OUT, len(seen), os.path.getsize(OUT))
