#!/usr/bin/env python3
"""Build public/words-pond.js for Word Pond.

POND_WORDS     - ENABLE word list (public domain), 2-15 letters, space separated.
                 The same dictionary classic word-tile games used; it is what
                 the player and Quackers are both checked against.
POND_AI_AVOID  - rude words Quackers will never play himself (players still can).

Usage:  python3 tools/build_pond.py
"""
import os
import re
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(ROOT, "tools", ".cache")
ENABLE_URL = "https://raw.githubusercontent.com/dolph/dictionary/master/enable1.txt"
BLOCK_URL = ("https://raw.githubusercontent.com/LDNOOBW/"
             "List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words/master/en")
EXTRA_AVOID = """
anal anus arse ass asses bitch bitches bong boob boobs butt butts cock cocks crap cum cunt cunts damn dick dicks dildo
dong fag fags fart farts fuck fucks gook homo jizz kike nazi nude nudes penis piss porn prick pube rape raped sex sexy
shit shits slut sluts spic tit tits turd twat whore whores
""".split()


def fetch(url, name):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, name)
    if not os.path.exists(path):
        urllib.request.urlretrieve(url, path)
    with open(path) as f:
        return [line.strip().lower() for line in f if line.strip()]


words = sorted({w for w in fetch(ENABLE_URL, "enable1.txt") if re.fullmatch(r"[a-z]{2,15}", w)})
try:
    block = {w for w in fetch(BLOCK_URL, "ldnoobw-en.txt") if re.fullmatch(r"[a-z]+", w)}
except Exception:
    block = set()
avoid = sorted((block | set(EXTRA_AVOID)) & set(words))

out = os.path.join(ROOT, "public", "words-pond.js")
with open(out, "w") as f:
    f.write("// Generated by tools/build_pond.py - do not edit by hand.\n")
    f.write('const POND_WORDS = "%s";\n' % " ".join(words))
    f.write('const POND_AI_AVOID = "%s";\n' % " ".join(avoid))
print(f"{len(words)} words, {len(avoid)} avoided -> {out} ({os.path.getsize(out)//1024} KB)")
